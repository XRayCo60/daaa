  O.opsById = function (id) {
    for (var i = 0; i < O.OPS_EVENTS.length; i++) {
      if (O.OPS_EVENTS[i].id === id) return O.OPS_EVENTS[i];
    }
    return null;
  };

  function cityOf(st, id) {
    for (var i = 0; i < st.cities.length; i++) {
      if (st.cities[i].id === id) return st.cities[i];
    }
    return null;
  }
  function ownerOf(st, id) {
    var c = cityOf(st, id);
    return c ? c.owner : null;
  }
  function emptyCity(st, id) {
    var c = cityOf(st, id);
    if (!c) return true;
    var r2 = O.CITY_R * O.CITY_R * 2.2;
    for (var i = 0; i < st.units.length; i++) {
      var u = st.units[i];
      if (u.fac !== c.owner) continue;
      var dx = u.x - c.x, dy = u.y - c.y;
      if (dx * dx + dy * dy < r2) return false;
    }
    return true;
  }
  function hasType(st, type) {
    for (var i = 0; i < st.units.length; i++) {
      if (st.units[i].type === type) return true;
    }
    return false;
  }
  function addRes(st, fac, d) {
    if (!d) return;
    var r = st.res[fac];
    r.i = Math.max(0, r.i + (d.i || 0));
    r.m = Math.max(0, r.m + (d.m || 0));
    r.o = Math.max(0, r.o + (d.o || 0));
  }
  function fireSpawn(st, sp) {
    if (!sp || !st._spawn) return;
    var city = cityOf(st, sp.city);
    if (!city) return;
    var n = sp.n || 1;
    var def = O.UNIT_TYPES[sp.cls];
    var pop = def ? def.pop : 1;
    for (var k = 0; k < n; k++) {
      if (st.pop(sp.fac) + pop > O.POP_CAP) break;
      st._spawn(sp.cls, sp.fac, city.x + 28 * k, city.y + 10);
    }
  }
  function cutRail(st, id) {
    var c = cityOf(st, id);
    if (!c) return;
    c.cut = true;
    c.sab = 1;
    if (st.alerts) st.alerts.push({ fac: c.owner, text: 'خط آهن ' + (O.cityById(id) ? O.cityById(id).nameFa : id) + ' قطع شد', ttl: 5 });
  }

  O.evalOpsWhen = function (st, expr) {
    var day = st.day | 0;
    var cease = st.ceasefire || O.CEASEFIRE;
    var season = O.season(day);
    var scenario = st.scenarioId || 'barbarossa';
    var vp = { ger: st._vpOf ? st._vpOf('ger') : 0, sov: st._vpOf ? st._vpOf('sov') : 0 };
    var res = st.res;
    function owner(id) { return ownerOf(st, id); }
    function empty(id) { return emptyCity(st, id); }
    function has(cls) { return hasType(st, cls); }
    try {
      return Function('day','cease','season','scenario','vp','res','owner','empty','has',
        'return (' + expr + ');')(day, cease, season, scenario, vp, res, owner, empty, has);
    } catch (err) {
      return false;
    }
  };

  O.applyOpsDay = function (st) {
    if (!st._opsFired) st._opsFired = {};
    var day = st.day | 0;
    for (var i = 0; i < O.OPS_EVENTS.length; i++) {
      var ev = O.OPS_EVENTS[i];
      var key = ev.once ? ev.id : (ev.id + ':' + day);
      if (st._opsFired[key]) continue;
      if (!O.evalOpsWhen(st, ev.when)) continue;
      st._opsFired[key] = 1;
      addRes(st, 'ger', ev.ger);
      addRes(st, 'sov', ev.sov);
      if (ev.spawn) fireSpawn(st, ev.spawn);
      if (ev.sabotage) cutRail(st, ev.sabotage);
      if (ev.extraSab && emptyCity(st, ev.extraSab)) cutRail(st, ev.extraSab);
      if (ev.oilCity) {
        var oc = cityOf(st, ev.oilCity);
        if (oc && oc.owner) addRes(st, oc.owner, { o: 10 });
      }
      if (ev.factory) {
        var fc = cityOf(st, ev.factory);
        if (fc && fc.owner) addRes(st, fc.owner, { m: 8 });
      }
      if (ev.raid) {
        var weak = st.res.ger.o <= st.res.sov.o ? 'ger' : 'sov';
        addRes(st, weak, { i: -3, m: -2 });
      }
      if (ev.logFa && st.alerts) st.alerts.push({ fac: null, text: ev.logFa, ttl: 5 });
      st.lastOps = { id: ev.id, title: ev.titleFa, day: day };
    }
  };
